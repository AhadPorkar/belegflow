export function translate(locale: Locale, key: string, variables: Record<string, string | number> = {}): string {
    const dictionary: Record<string, string> = messages[locale];
    let text = dictionary[key] ?? (key.startsWith('error_') ? dictionary.errorGeneric : key);
    for (const [name, value] of Object.entries(variables))
        text = text.replaceAll('{' + name + '}', String(value));
    return text;
}
